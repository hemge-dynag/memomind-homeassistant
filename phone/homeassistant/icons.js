// The numeric id sent over the wire to the glasses: index in ICON_NAMES.
export function iconId(name) {
  const at = ICON_NAMES.indexOf(name);
  return at >= 0 ? at : -1;
}

export function isKnownIcon(name) {
  return typeof name === "string" && Object.prototype.hasOwnProperty.call(PATHS, name);
}

// Inline SVG markup for a known icon, or "" when unknown. The fill follows
// the surrounding text colour so it blends with labels on either background.
export function iconSvg(name, size = 18) {
  const d = PATHS[name];
  if (!d) return "";
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true" focusable="false"><path fill="currentColor" d="${d}"/></svg>`;
}

// Builds the inline SVG as a DOM node (avoids innerHTML for untrusted data).
export function iconNode(name, size = 18) {
  const d = PATHS[name];
  if (!d) return null;
  const ns = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(ns, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  const path = document.createElementNS(ns, "path");
  path.setAttribute("fill", "currentColor");
  path.setAttribute("d", d);
  svg.append(path);
  return svg;
}

